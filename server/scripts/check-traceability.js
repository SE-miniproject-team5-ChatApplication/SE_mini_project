// Backlog items in the "Stretch" column: missing tests are warnings, not errors.
const STRETCH = new Set(['TC-HIS-03', 'TC-NOT-02', 'TC-PERF-01', 'TC-PERF-04', 'TC-USAB-01', 'TC-RCP-02']);

function filesUnder(dir, exts) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) return e.name === 'node_modules' ? [] : filesUnder(full, exts);
    return exts.some((x) => e.name.endsWith(x)) ? [full] : [];
  });
}

function findCoverage() {
  const sources = [
    ...filesUnder(path.join(ROOT, 'server', 'tests'), ['.test.js']),
    ...filesUnder(path.join(ROOT, 'server', 'scripts', 'perf'), ['.js']).filter((f) => !f.endsWith('lib.js')),
    ...filesUnder(path.join(ROOT, 'docs', 'testing'), ['.md']),
  ];
  const found = {};
  for (const file of sources) {
    const text = fs.readFileSync(file, 'utf8');
    for (const id of Object.keys(TEST_CASES)) {
      if (text.includes(id)) (found[id] = found[id] || []).push(path.relative(ROOT, file).replace(/\\/g, '/'));
    }
  }
  return found;
}

function main() {
  const found = findCoverage();
  let failures = 0;
  const rows = Object.entries(TEST_CASES).map(([id, reqs]) => {
    const where = found[id] || [];
    let status = 'covered';
    if (where.length === 0) {
      status = STRETCH.has(id) ? 'stretch - not yet' : 'MISSING';
      if (!STRETCH.has(id)) failures += 1;
    }
    console.log(`${status === 'covered' ? 'OK  ' : status === 'MISSING' ? 'FAIL' : 'WARN'}  ${id.padEnd(11)} ${reqs.padEnd(32)} ${where.join(', ')}`);
    return `| ${id} | ${reqs} | ${where.map((w) => `\`${w}\``).join('<br>') || status} |`;
  });

  if (process.argv.includes('--write')) {
    const md = [
      '# Test traceability (NFR-QA-5)',
      '',
      'Generated by `npm run trace -- --write` from the Test Plan (Appendix A).',
      'Every automated test title starts with its TC id, so `npx jest -t TC-MSG-01` runs that case.',
      '',
      '| Test case | Requirements | Where it is tested |',
      '|---|---|---|',
      ...rows,
      '',
    ].join('\n');
    fs.writeFileSync(path.join(ROOT, 'docs', 'TRACEABILITY.md'), md);
    console.log('docs/TRACEABILITY.md written');
  }
  console.log(failures === 0 ? '\nAll planned test cases are implemented.' : `\n${failures} test case(s) missing.`);
  process.exit(failures === 0 ? 0 : 1);
}

main();
